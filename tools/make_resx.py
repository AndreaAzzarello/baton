def placeholders(text):
    return sorted(set(re.sub(r":[^}]*", "", m) for m in re.findall(r"\{\d+(?::[^}]*)?\}", text)))

bad = [k for k, (en, it) in S.items() if placeholders(en) != placeholders(it)]
if bad:
    sys.exit("placeholders differ: " + ", ".join(bad))

ACCENTS = str.maketrans("aceinousyACEINOUSY", "àçéîñöüšýÀÇÉÎÑÖÜŠÝ")

def pseudo(text):
    # Placeholders, format strings ("Programs (*.exe)|*.exe") and line breaks stay as they are; the rest grows by 40%.
    if "|" in text:
        return text
    parts = re.split(r"(\{[^}]*\}|\n)", text)
    body = "".join(p if re.fullmatch(r"\{[^}]*\}|\n", p) else p.translate(ACCENTS) for p in parts)
    return "[" + body + " " + "~" * max(1, round(len(text) * 0.4)) + "]"

def write(name, values):
    out = ['<?xml version="1.0" encoding="utf-8"?>', "<root>",
           '  <resheader name="resmimetype"><value>text/microsoft-resx</value></resheader>',
           '  <resheader name="version"><value>2.0</value></resheader>',
           '  <resheader name="reader"><value>System.Resources.ResXResourceReader, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089</value></resheader>',
           '  <resheader name="writer"><value>System.Resources.ResXResourceWriter, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089</value></resheader>']
    for k in sorted(values):
        out.append(f'  <data name="{k}" xml:space="preserve"><value>{escape(values[k])}</value></data>')
    out.append("</root>")
    target = root / "Baton.Core" / "Resources" / name
    target.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")  # LF as in the repository (.gitattributes)
    print(f"{len(values)} strings -> {target}")

